"""账号规范的公共实现。

作用：让账号创建和登录请求校验遵循同一套大小写、空白和字符规则。
调用位置：app.cli 的创建用户流程，以及 app.schemas.auth 的登录输入模型。
原因：规则分散会产生能够创建却无法登录、或大小写不同却被认为是不同人的账号。
"""

import re  # 用完整匹配检查账号允许的字符和长度，避免只检查到字符串的一部分。


def normalize_account(account: str) -> str:  # 接收创建或登录流程提供的账号，返回可用于数据库查询的统一形式。
    """作用：去除账号首尾空白、统一小写，并校验账号格式。

    调用位置：创建用户命令与 LoginRequest.normalize_account 共同调用。
    原因：创建与登录必须用同一个唯一标识规则，否则输入形式不同会造成身份不一致。
    参数：account 是尚未规范化的账号字符串；密码不经过这个函数处理。
    返回：规范化后的账号；不符合约定时抛出 ValueError 交给调用方处理。
    """
    normalized = account.strip().lower()  # 仅规范化账号的无意义空白和大小写，密码的原始字符必须另外保留。
    if re.fullmatch(r"[a-z0-9][a-z0-9_.-]{2,63}", normalized) is None:  # 要求整个账号为 3 至 64 位，且首位是字母或数字。
        raise ValueError("账号须为 3 至 64 位，以字母或数字开头，仅允许字母、数字、下划线、点和连字符。")  # 明确拒绝无效账号，避免不合法标识进入数据库或查询过程。
    return normalized  # 将创建和登录都认可的账号交回调用方。
